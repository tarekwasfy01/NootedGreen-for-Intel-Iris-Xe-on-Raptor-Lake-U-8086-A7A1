#pragma once
#include <stdint.h>
namespace HPHDMI {
// Final output stage only. Caller must hold the donor workloop and resource
// reservations, supply a live valid EDID and prepare PLL/PHY/pipe/plane first.
// This does not allocate DBUF, program a PLL, or fabricate DP link status.
class Output {
public:
 enum class Result : uint32_t { Ready, Preconditions, Inaccessible, Busy, ReadbackFailed };
 struct Admission {
  bool ownsResources=false, liveEdid=false, clockReady=false, phyReady=false;
  bool planeReady=false, dbufReady=false;
  uint32_t width=0,height=0,clockKHz=0,bpc=0;
 };
 template<class Io> Result enable(Io &io,const Admission &a) {
  if(!a.ownsResources||!a.liveEdid||!a.clockReady||!a.phyReady||
     !a.planeReady||!a.dbufReady||a.width!=1920||a.height!=1080||
     a.clockKHz!=148500||a.bpc!=8)return Result::Preconditions;
  if(active)return Result::Busy;
  for(unsigned n=0;n<Count;++n) {
   saved[n]=io.read(regs[n]);
   if(saved[n]==0xffffffffu)return Result::Inaccessible;
  }
  // Never seize an output already enabled by another owner.
  if(saved[0]&0x80000000u)return Result::Busy;
  // Apple must already have committed a running B pipe and enabled plane.
  if((io.read(0x71008)&0xc0000000u)!=0xc0000000u||
     !(io.read(0x71180)&0x80000000u))return Result::Preconditions;
  io.write(0x61200,0); // disable packet transmission while updating AVI
  // HP Linux 1080p60 RGB AVI packet. ECC is generated by hardware.
  constexpr uint32_t avi[8]={0xd0282,0x4281221,0x10,0x0,0x0,0x0,0x0,0x0};
  for(unsigned n=0;n<8;++n)io.write(0x61220+4*n,avi[n]);
  io.write(0x46144,0x20000000); // transcoder B selects DDI B clock
  io.write(0x61400,0x90030000); // B, HDMI, 8 bpc; HP measured mode
  io.write(0x61200,0x11001); // HP measured AVI packet enables
  io.write(0x64100,saved[0]|0x80000000u);
  (void)io.read(0x64100); // posting read
  if(io.read(0x61400)!=0x90030000u||
     !(io.read(0x64100)&0x80000000u)) {
   restore(io);return Result::ReadbackFailed;
  }
  active=true;return Result::Ready;
 }
 template<class Io> bool disable(Io &io,bool ownsResources) {
  if(!active||!ownsResources)return false;
  // Do not replay saved state after another owner has changed the route.
  if(io.read(0x61400)!=0x90030000u)return false;
  restore(io);active=false;return true;
 }
private:
 static constexpr unsigned Count=12;
 const uint32_t regs[Count]={0x64100,0x46144,0x61400,0x61200,
  0x61220,0x61224,0x61228,0x6122c,0x61230,0x61234,0x61238,0x6123c};
 uint32_t saved[Count]={};bool active=false;
 template<class Io> void restore(Io &io) {
  io.write(0x64100,io.read(0x64100)&~0x80000000u);
  (void)io.read(0x64100);
  io.write(0x61200,0);
  for(unsigned n=4;n<Count;++n)io.write(regs[n],saved[n]);
  io.write(0x61400,saved[2]);io.write(0x46144,saved[1]);
  io.write(0x61200,saved[3]);io.write(0x64100,saved[0]);
 }
};
}
